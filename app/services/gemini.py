import time
import logging
from typing import Literal
from google import genai
from google.genai import types
from google.genai.errors import APIError

from app.core.config import settings

logger = logging.getLogger(__name__)

# Initialize the Gemini client using the API key from settings
gemini_client = genai.Client(api_key=settings.GEMINI_API_KEY)


def embed_texts(
    texts: list[str],
    task_type: Literal["RETRIEVAL_DOCUMENT", "RETRIEVAL_QUERY"] = "RETRIEVAL_DOCUMENT",
    batch_size: int = 10,
    max_retries: int = 5,
    base_backoff_seconds: float = 2.0,
) -> list[list[float]]:
    """
    Computes text embeddings using Google Gemini's embedding model.
    Processes texts in batches and uses exponential backoff to handle free-tier rate limits.
    """
    if not texts:
        return []

    all_embeddings: list[list[float]] = []

    # Process in batches to stay within API payload and request limits
    for i in range(0, len(texts), batch_size):
        batch = texts[i : i + batch_size]
        attempt = 0
        success = False

        while attempt < max_retries and not success:
            try:
                response = gemini_client.models.embed_content(
                    model=settings.EMBEDDING_MODEL,
                    contents=batch,
                    config=types.EmbedContentConfig(
                        task_type=task_type,
                        output_dimensionality=768,
                    ),
                )
                # Each embedding in response.embeddings has a .values attribute (list of floats)
                for item in response.embeddings:
                    all_embeddings.append(item.values)
                success = True

            except APIError as e:
                attempt += 1
                if attempt >= max_retries:
                    logger.error(f"Failed to embed batch after {max_retries} attempts: {e}")
                    raise RuntimeError(f"Gemini Embedding API failed after retries: {str(e)}") from e

                sleep_time = base_backoff_seconds * (2 ** (attempt - 1))
                logger.warning(
                    f"Gemini API rate limit or error encountered (attempt {attempt}/{max_retries}). "
                    f"Retrying in {sleep_time:.1f}s... Details: {e}"
                )
                time.sleep(sleep_time)

            except Exception as e:
                logger.error(f"Unexpected error while calling Gemini embedding: {e}")
                raise

    return all_embeddings


def embed_query(query: str) -> list[float]:
    """
    Helper to embed a single query with task_type RETRIEVAL_QUERY.
    """
    result = embed_texts([query], task_type="RETRIEVAL_QUERY")
    if not result:
        raise ValueError("Failed to generate embedding for query.")
    return result[0]


def generate_rag_answer(
    question: str,
    context_chunks: list[dict],
    max_retries: int = 3,
    base_backoff_seconds: float = 2.0,
) -> str:
    """
    Generates an answer using Gemini Flash based on retrieved document chunks.
    Injects context with filenames and page numbers, and applies retry logic.
    """
    if not context_chunks:
        return "I could not find any relevant information in your uploaded documents to answer this question."

    # Format the context chunks with citations
    context_sections: list[str] = []
    for idx, chunk in enumerate(context_chunks, 1):
        context_sections.append(
            f"--- Document Excerpt {idx} ---\n"
            f"File: {chunk.get('filename')}\n"
            f"Page: {chunk.get('page')}\n"
            f"Content:\n{chunk.get('text')}\n"
        )
    formatted_context = "\n".join(context_sections)

    system_instruction = (
        "You are an accurate, reliable RAG (Retrieval-Augmented Generation) assistant. "
        "Answer the user's question using ONLY the provided document excerpts. "
        "Explicitly cite the source filename and page number for each key point in your answer. "
        "If the answer cannot be determined from the provided excerpts, politely state that the "
        "information is not available in the uploaded documents. Do not speculate or use outside knowledge."
    )

    user_prompt = (
        f"Context Excerpts:\n{formatted_context}\n\n"
        f"User Question: {question}\n\n"
        "Please provide a clear and well-structured answer citing your sources."
    )

    attempt = 0
    while attempt < max_retries:
        try:
            response = gemini_client.models.generate_content(
                model=settings.LLM_MODEL,
                contents=user_prompt,
                config=types.GenerateContentConfig(
                    system_instruction=system_instruction,
                    temperature=0.2,
                ),
            )
            return response.text or "No response generated by model."

        except APIError as e:
            attempt += 1
            if attempt >= max_retries:
                logger.error(f"Failed to generate answer after {max_retries} attempts: {e}")
                raise RuntimeError(f"Gemini LLM API failed after retries: {str(e)}") from e

            sleep_time = base_backoff_seconds * (2 ** (attempt - 1))
            logger.warning(
                f"Gemini LLM API rate limit or error (attempt {attempt}/{max_retries}). "
                f"Retrying in {sleep_time:.1f}s... Details: {e}"
            )
            time.sleep(sleep_time)

        except Exception as e:
            logger.error(f"Unexpected error during answer generation: {e}")
            raise

    return "Unable to generate an answer at this time due to API limits."


def generate_conversational_rag_answer(
    question: str,
    context_chunks: list[dict],
    chat_history: list[dict],
    max_retries: int = 3,
    base_backoff_seconds: float = 2.0,
) -> str:
    """
    Generates an answer using Gemini Flash taking into account:
    1. Past conversation turns (memory).
    2. Newly retrieved document chunks with citation metadata.
    Includes exponential backoff retry.
    """
    # 1. Format document context
    if context_chunks:
        context_sections: list[str] = []
        for idx, chunk in enumerate(context_chunks, 1):
            context_sections.append(
                f"--- Document Excerpt {idx} ---\n"
                f"File: {chunk.get('filename')}\n"
                f"Page: {chunk.get('page')}\n"
                f"Content:\n{chunk.get('text')}\n"
            )
        formatted_context = "\n".join(context_sections)
    else:
        formatted_context = "No relevant document excerpts were found in the user's library."

    # 2. Format past conversation history
    history_sections: list[str] = []
    for msg in chat_history:
        role_label = "User" if msg.get("role") == "user" else "Assistant"
        history_sections.append(f"{role_label}: {msg.get('content')}")
    formatted_history = "\n".join(history_sections) if history_sections else "No previous conversation history."

    system_instruction = (
        "You are an accurate, helpful conversational RAG (Retrieval-Augmented Generation) assistant. "
        "You maintain conversational context from previous messages while answering user questions. "
        "Ground all factual statements strictly in the provided document excerpts. "
        "Explicitly cite the source filename and page number for facts derived from documents (e.g. [Report.pdf, Page 3]). "
        "If the document excerpts do not contain the answer, politely inform the user that the information "
        "cannot be found in their uploaded documents, while remaining conversational and helpful based on prior chat history. "
        "Do not fabricate facts or invent citations."
    )

    user_prompt = (
        f"=== Prior Conversation History ===\n"
        f"{formatted_history}\n\n"
        f"=== Document Context Excerpts ===\n"
        f"{formatted_context}\n\n"
        f"=== Current User Question ===\n"
        f"{question}\n\n"
        "Please provide a well-structured, coherent response citing relevant sources where appropriate."
    )

    attempt = 0
    while attempt < max_retries:
        try:
            response = gemini_client.models.generate_content(
                model=settings.LLM_MODEL,
                contents=user_prompt,
                config=types.GenerateContentConfig(
                    system_instruction=system_instruction,
                    temperature=0.2,
                ),
            )
            return response.text or "No response generated by model."

        except APIError as e:
            attempt += 1
            if attempt >= max_retries:
                logger.error(f"Failed to generate conversational answer after {max_retries} attempts: {e}")
                raise RuntimeError(f"Gemini LLM API failed after retries: {str(e)}") from e

            sleep_time = base_backoff_seconds * (2 ** (attempt - 1))
            logger.warning(
                f"Gemini LLM API rate limit or error (attempt {attempt}/{max_retries}). "
                f"Retrying in {sleep_time:.1f}s... Details: {e}"
            )
            time.sleep(sleep_time)

        except Exception as e:
            logger.error(f"Unexpected error during conversational answer generation: {e}")
            raise

    return "Unable to generate an answer at this time due to API limits."


